"""
Renders benchmark results into a genuine multi-page HTML dashboard:
one folder containing index.html, one page per model, a comparison
page, and an "insights" page with click-to-reveal explanations.

The insights page is NOT a live LLM chat. A real chat would need
either a network call to an external API (which breaks the "runs
offline, on-device" story this whole project is about) or a local
llama-server (which does not currently cross-compile for Android in
this llama.cpp version, see DEMO.md/README known limitations). Instead,
every "explanation" is generated by fixed JS logic reading the run's
own embedded JSON data, so every answer is guaranteed accurate to the
actual numbers, zero hallucination risk, fully offline, no server.

All pages are plain static HTML/CSS/JS, opened directly from disk
(file://), no build step, no server required, consistent with the
rest of this project's dependencies.
"""

