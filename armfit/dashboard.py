def _render_insights(model_ids, report_data_json) -> str:
    questions = [
        ("recommendation", "Which configuration should I use?"),
        ("mechanism", "Why is KleidiAI faster on quantized formats but not F16?"),
        ("baselineQuant", "Why doesn't quantization alone speed things up here?"),
        ("methodology", "How were these numbers actually measured?"),
        ("ttft", "What does TTFT mean?"),
    ]
    if len(model_ids) > 1:
        questions.insert(2, ("crossModel", "Does the speedup hold across model sizes?"))

    buttons = "".join(
        f'<button class="q-btn" onclick="toggleAnswer(\'{key}\', this)">{q}</button>'
        f'<div class="answer" id="answer-{key}"></div>'
        for key, q in questions
    )

    body = f'''
    <header class="page-header">
      <h1>Insights</h1>
      <div class="meta">Click a question — every answer is generated from this run's actual measured data, not a live model.</div>
    </header>
    <div class="panel">{buttons}</div>
    '''
    html = _page_shell("Insights", "insights", model_ids, body, report_data_json)
    # Insert the insights JS logic right before </body>, kept separate from
    # the f-string page shell above specifically to avoid brace-escaping.
    return html.replace("</body>", f"<script>{_INSIGHTS_JS}</script>\n</body>")


