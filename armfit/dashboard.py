def generate_dashboard(
    model_ids: List[str],
    device_serial: str,
    free_ram_mb: int,
    ranked: List[Dict],
    recommendations: Dict[str, Dict],
    output_dir: Path,
) -> Path:
    """
    Writes a multi-page dashboard into output_dir and returns the path to
    index.html (the entry point to open). Creates output_dir if needed.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    by_model: Dict[str, List[Dict]] = {}
    for r in ranked:
        by_model.setdefault(r["model"], []).append(r)

    has_quality = any(r.get("perplexity") is not None for r in ranked)

    report_data_json = json.dumps({
        "models": model_ids,
        "device": device_serial,
        "free_ram_mb": free_ram_mb,
        "results": ranked,
        "recommendations": recommendations,
    }, indent=2)

    (output_dir / "index.html").write_text(
        _render_index(model_ids, device_serial, free_ram_mb, by_model, recommendations, report_data_json),
        encoding="utf-8",
    )

    for model_id in model_ids:
        model_results = by_model.get(model_id, [])
        rec = recommendations.get(model_id, {})
        (output_dir / f"model_{slugify(model_id)}.html").write_text(
            _render_model_page(model_id, model_results, rec, has_quality, model_ids, report_data_json),
            encoding="utf-8",
        )

    if len(model_ids) > 1:
        (output_dir / "comparison.html").write_text(
            _render_comparison(model_ids, by_model, report_data_json),
            encoding="utf-8",
        )

    (output_dir / "insights.html").write_text(
        _render_insights(model_ids, report_data_json),
        encoding="utf-8",
    )

    return output_dir / "index.html"