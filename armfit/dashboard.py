def _fmt(value, suffix: str = "") -> str:
    if value is None:
        return "n/a"
    return f"{value}{suffix}"


def slugify(model_id: str) -> str:
    """Turns a HF model id into a safe filename fragment, e.g.
    'Qwen/Qwen2.5-0.5B-Instruct' -> 'qwen-qwen2-5-0-5b-instruct'."""
    s = model_id.lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def short_label(model_id: str) -> str:
    """Turns a HF model id into a short nav-bar label, e.g.
    'Qwen/Qwen2.5-0.5B-Instruct' -> 'Qwen2.5-0.5B'."""
    name = model_id.split("/")[-1]
    return re.sub(r"-Instruct$", "", name)


def _decode_chart_svg(model_results: List[Dict]) -> str:
    by_quant: Dict[str, Dict[str, Dict]] = {}
    for r in model_results:
        by_quant.setdefault(r["quant"], {})[r["build"]] = r

    quants = sorted(by_quant.keys())
    values = []
    for q in quants:
        b = by_quant[q].get("baseline", {}).get("decode_tps")
        k = by_quant[q].get("kleidiai", {}).get("decode_tps")
        values.append((q, b, k))

    plottable = [v for _, b, k in values for v in (b, k) if v is not None]
    if not plottable:
        return (f'<svg viewBox="0 0 {_CHART_W} {_CHART_H}" class="chart">'
                f'<text x="{_CHART_W/2}" y="{_CHART_H/2}" class="chart-empty" '
                f'text-anchor="middle">No decode tok/s data to chart</text></svg>')

    max_val = max(plottable) * 1.15
    plot_h = _CHART_H - _CHART_TOP_PAD - _CHART_BOTTOM_PAD
    group_w = _BAR_W * 2 + _BAR_GAP
    total_w = len(values) * (group_w + _BAR_GROUP_GAP) - _BAR_GROUP_GAP
    x_start = (_CHART_W - total_w) / 2

    parts = [f'<svg viewBox="0 0 {_CHART_W} {_CHART_H}" class="chart">']
    baseline_x = x_start
    for q, b, k in values:
        for val, cls, offset in ((b, "bar-baseline", 0), (k, "bar-kleidiai", _BAR_W + _BAR_GAP)):
            bar_x = baseline_x + offset
            if val is not None:
                bar_h = (val / max_val) * plot_h
                bar_y = _CHART_TOP_PAD + (plot_h - bar_h)
                parts.append(
                    f'<rect x="{bar_x:.1f}" y="{bar_y:.1f}" width="{_BAR_W}" height="{bar_h:.1f}" class="{cls}"/>'
                )
                parts.append(
                    f'<text x="{bar_x + _BAR_W/2:.1f}" y="{bar_y - 5:.1f}" class="bar-label" '
                    f'text-anchor="middle">{val:.1f}</text>'
                )
        parts.append(
            f'<text x="{baseline_x + group_w/2:.1f}" y="{_CHART_H - 10}" class="axis-label" '
            f'text-anchor="middle">{q}</text>'
        )
        baseline_x += group_w + _BAR_GROUP_GAP

    parts.append("</svg>")
    return "".join(parts)


def _best_kleidiai_speedup(model_results: List[Dict]):
    by_quant: Dict[str, Dict[str, Dict]] = {}
    for r in model_results:
        by_quant.setdefault(r["quant"], {})[r["build"]] = r
    best = None
    for quant, builds in by_quant.items():
        base = builds.get("baseline")
        kleidiai = builds.get("kleidiai")
        if base and kleidiai and base.get("decode_tps") and kleidiai.get("decode_tps"):
            ratio = kleidiai["decode_tps"] / base["decode_tps"]
            if best is None or ratio > best[1]:
                best = (quant, ratio)
    return best


