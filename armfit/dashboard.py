def _navbar(current: str, model_ids: List[str]) -> str:
    items: List[Tuple[str, str, str]] = [("index.html", "Overview", "index")]
    for m in model_ids:
        items.append((f"model_{slugify(m)}.html", short_label(m), f"model_{slugify(m)}"))
    if len(model_ids) > 1:
        items.append(("comparison.html", "Comparison", "comparison"))
    items.append(("insights.html", "Insights", "insights"))

    links = "".join(
        f'<a href="{href}" class="{"active" if key == current else ""}">{label}</a>'
        for href, label, key in items
    )
    return f'<nav class="navbar"><span class="brand">ARM<span>FIT</span></span>{links}</nav>'


